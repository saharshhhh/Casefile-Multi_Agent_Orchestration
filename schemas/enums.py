from enum import Enum

class Verdict(str, Enum):
    APPROVE_RECOMMEND = "APPROVE_RECOMMEND"
    SEND_BACK = "SEND_BACK"
    ESCALATE = "ESCALATE"

class SendBackReason(str, Enum):
    MISSING_PRIOR_CLAIM_CHECK = "MISSING_PRIOR_CLAIM_CHECK"
    ESTIMATE_UNSUPPORTED = "ESTIMATE_UNSUPPORTED"
    POLICY_LIMIT_UNCLEAR = "POLICY_LIMIT_UNCLEAR"

class AnomalyFlag(str, Enum):
    ESTIMATE_ABOVE_BENCHMARK = "ESTIMATE_ABOVE_BENCHMARK"
    DUPLICATE_CLAIM_SUSPECTED = "DUPLICATE_CLAIM_SUSPECTED"
    LIMIT_EXCEEDED = "LIMIT_EXCEEDED"

class RunStatus(str, Enum):
    RUNNING = "RUNNING"
    AWAITING_APPROVAL = "AWAITING_APPROVAL"
    DONE = "DONE"
    ESCALATED = "ESCALATED"
    REJECTED = "REJECTED"